"""Report Generation Service exporting system analytics, audits, and evaluation metrics."""
import json
from datetime import datetime
from typing import Dict, Any, List
import pandas as pd

from database.repository import Repository
from config import APP_TITLE, APP_VERSION

class ReportService:
    @staticmethod
    def generate_executive_report_json() -> str:
        """Generates an executive platform intelligence report in JSON format."""
        kpis = Repository.get_system_kpis()
        issues = Repository.get_issues()
        recent_analyses = Repository.get_recent_analyses(limit=25)
        audit_events = Repository.get_audit_logs(limit=25)

        payload = {
            "application": APP_TITLE,
            "version": APP_VERSION,
            "generated_at": datetime.now().isoformat(),
            "kpi_metrics": kpis,
            "decision_center_issues_count": len(issues),
            "high_priority_issues": [i for i in issues if i["priority_score"] >= 65],
            "recent_review_sample": recent_analyses[:5],
            "recent_audit_trail": audit_events[:5]
        }
        return json.dumps(payload, indent=2)

    @staticmethod
    def generate_executive_report_markdown() -> str:
        """Generates an executive markdown report for stakeholders."""
        kpis = Repository.get_system_kpis()
        issues = Repository.get_issues()

        md = f"""# Executive Intelligence & Decision Support Report
**Platform:** {APP_TITLE} (v{APP_VERSION})  
**Report Date:** {datetime.now().strftime('%B %d, %Y - %H:%M UTC')}

---

## 1. Executive Summary & KPIs
- **Total Customer Reviews Analyzed:** {kpis['total_analyzed']:,}
- **Positive Sentiment Ratio:** {kpis['positive_percentage']:.1f}% ({kpis['total_positive']:,} reviews)
- **Negative Sentiment Ratio:** {kpis['negative_percentage']:.1f}% ({kpis['total_negative']:,} reviews)
- **Active Tracked Business Issues:** {kpis['active_issues']}
- **High-Priority Escalations:** {kpis['high_priority_issues']}

---

## 2. Priority Business Issues
| ID | Category | Severity | Priority Score | Status | Recommended Action |
|:---|:---|:---|:---|:---|:---|
"""
        for issue in issues[:10]:
            md += f"| #{issue['id']} | {issue['category']} | {issue['severity']} | **{issue['priority_score']}** | {issue['status']} | {issue['recommended_action'][:60]}... |\n"

        md += """
---
## 3. Governance & System Integrity
- All sentiment predictions generated by trained and calibrated ML / Deep Learning models.
- Business recommendations derived via rule-based expert system reasoning.
- Full audit log persisted in SQLite database.
"""
        return md

    @staticmethod
    def export_issues_csv() -> str:
        issues = Repository.get_issues()
        if not issues:
            return ""
        df = pd.DataFrame(issues)
        return df.to_csv(index=False)

    @staticmethod
    def export_audit_log_csv() -> str:
        logs = Repository.get_audit_logs(limit=500)
        if not logs:
            return ""
        df = pd.DataFrame(logs)
        return df.to_csv(index=False)
